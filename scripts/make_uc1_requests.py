"""Generate the fixed UC.1 request set for the §10.4 measurement runs.

Writes measurements/uc1_requests.json: N driver requests, each as a message
template (Scenario 1, the model reads it) and the same six fields as the
driver would type them into the form (Scenario 2, and the Scenario 1 fallback).

Times are stored as offsets from the moment a run starts, because A1.1 only
accepts an arrival within 60 minutes of submission (SPEC Data Contract
section 5). scripts/measure_uc1.py fills in the clock times at run time.

The set is synthetic and reproducible: python scripts/make_uc1_requests.py
always writes the same file for the same seed and count.

Usage: python scripts/make_uc1_requests.py [--count 40] [--seed 5151]
"""

import argparse
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from contextual_information_sources import get_destinations  # noqa: E402

OUT = ROOT / "measurements" / "uc1_requests.json"

VEHICLES = {"sedan": ["a sedan", "my sedan", "a car"], "suv": ["an SUV", "my SUV"], "van": ["a van", "a minivan"]}
ELIGIBILITY = {"permit_O": ["I have an O permit", "O permit holder", "with my O permit"],
               "visitor": ["I'm a visitor", "visitor parking please", "I'll pay hourly as a visitor"]}
ACCESS = {False: ["no accessible space needed", "I don't need an accessible spot", "no accessibility needs"],
          True: ["I need an accessible space", "accessible parking required"]}

# {dest} {arrive} {leave} {stay} {vehicle} {elig} {access}
TEMPLATES_LEAVE = [
    "I need to park near {dest} at {arrive} and leave at {leave}. {vehicle}, {elig}, {access}.",
    "Going to {dest}, arriving {arrive}, out by {leave}. Driving {vehicle}; {elig}; {access}.",
    "Parking for {dest} from {arrive} to {leave} please. {vehicle}, {elig}, {access}.",
]
TEMPLATES_STAY = [
    "I'll get to {dest} around {arrive} and stay {stay}. I drive {vehicle}, {elig}, and {access}.",
    "Need a spot near {dest} at {arrive} for {stay}, {vehicle}, {elig}, {access}.",
]
STAYS = {60: "one hour", 90: "an hour and a half", 120: "two hours", 180: "three hours", 240: "four hours"}


def make(count: int, seed: int) -> list[dict]:
    rng = random.Random(seed)
    destinations = get_destinations()
    requests = []
    for i in range(count):
        vehicle = rng.choice(list(VEHICLES))
        eligibility = rng.choice(list(ELIGIBILITY))
        access = rng.random() < 0.15
        stay = rng.choice(list(STAYS))
        uses_stay = rng.random() < 0.4
        template = rng.choice(TEMPLATES_STAY if uses_stay else TEMPLATES_LEAVE)
        destination = rng.choice(destinations)
        message = (template
                   .replace("{dest}", destination)
                   .replace("{vehicle}", rng.choice(VEHICLES[vehicle]))
                   .replace("{elig}", rng.choice(ELIGIBILITY[eligibility]))
                   .replace("{access}", rng.choice(ACCESS[access]))
                   .replace("{stay}", STAYS[stay]))
        requests.append({
            "id": f"R{i + 1:02d}",
            "message_template": message,
            "form": {
                "destination": destination,
                "arrive_in_minutes": rng.choice([10, 15, 20, 30, 40, 45]),
                "stay_minutes": stay,
                "vehicle_category": vehicle,
                "declared_eligibility": eligibility,
                "access_needs": access,
            },
        })
    return requests


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--count", type=int, default=40)
    parser.add_argument("--seed", type=int, default=5151)
    args = parser.parse_args()
    OUT.parent.mkdir(exist_ok=True)
    payload = {
        "description": "Synthetic UC.1 driver requests for Lab Manual 10.4 measurement runs. "
                       "Generated by scripts/make_uc1_requests.py; not real driver data.",
        "seed": args.seed,
        "placeholders": {"{arrive}": "clock time now + arrive_in_minutes",
                         "{leave}": "clock time arrive + stay_minutes"},
        "requests": make(args.count, args.seed),
    }
    OUT.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"wrote {len(payload['requests'])} requests to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
